// Generates TypeScript types for every registry model from Router's per-model
// OpenAPI document (spec: Rules for every call, 7). Documents are cached by
// ETag in .schema-cache/ (gitignored), so an unchanged schema costs one 304.
// Adapters import these types, so a schema change breaks the build.
// Usage: npm run gen:schemas   (reads COMFY_API_KEY from the shell)
import "./lib/env.ts";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";
import { REGISTRY } from "../src/lib/registry/models.ts";
import * as router from "../src/lib/router/client.ts";
import { useShellKey } from "./lib/router-script.ts";

const CACHE_DIR = ".schema-cache";
const OUT_DIR = "src/lib/registry/schemas";

useShellKey();
mkdirSync(CACHE_DIR, { recursive: true });
mkdirSync(OUT_DIR, { recursive: true });

// vertexai/gemini-nano-banana-2.1 -> vertexai-gemini-nano-banana-2-1
const slug = (id: string) => id.toLowerCase().replace(/[^a-z0-9]+/g, "-");
// vertexai/gemini-nano-banana-2.1 -> VertexaiGeminiNanoBanana21
const namespace = (id: string) => slug(id).split("-").map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join("");

interface Cached {
  etag: string | null;
  document: unknown;
}

const exports: string[] = [];
let failed = 0;

for (const entry of REGISTRY) {
  const cachePath = `${CACHE_DIR}/${slug(entry.id)}.json`;
  const cached: Cached | undefined = existsSync(cachePath) ? JSON.parse(readFileSync(cachePath, "utf8")) : undefined;
  process.stdout.write(`${entry.id} ... `);
  try {
    const res = await router.modelSchema(entry.id, cached?.etag);
    let document = cached?.document;
    if (res.unchanged) {
      console.log("unchanged");
    } else {
      document = res.document;
      writeFileSync(cachePath, JSON.stringify({ etag: res.etag, document } satisfies Cached));
      console.log(cached ? "updated" : "fetched");
    }
    const ast = await openapiTS(document as Parameters<typeof openapiTS>[0]);
    const header = `// Generated by scripts/gen-schema-types.ts from Router's OpenAPI document for\n// ${entry.id}. Don't edit; rerun npm run gen:schemas.\n\n`;
    writeFileSync(`${OUT_DIR}/${slug(entry.id)}.ts`, header + astToString(ast));
    exports.push(`export type * as ${namespace(entry.id)} from "./${slug(entry.id)}";`);
  } catch (err) {
    failed++;
    console.log(`failed: ${(err as Error).message}`);
  }
}

writeFileSync(
  `${OUT_DIR}/index.ts`,
  `// Generated by scripts/gen-schema-types.ts. Don't edit.\n\n${exports.sort().join("\n")}\n`,
);
console.log(`Wrote ${exports.length} schema modules to ${OUT_DIR}/`);
if (failed) process.exit(1);
