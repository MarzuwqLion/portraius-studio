// Keeps the ComfyUI node pack (custom_nodes/comfyui-portraius-characters) in
// step with the app: its camera and look presets, and the prompts its Python
// port of the compiler must reproduce word for word. After changing a preset
// or the compiler, regenerate with: npm run nodepack
import { existsSync, readFileSync, writeFileSync } from "fs";
import { describe, expect, it } from "vitest";
import { CAMERA, LOOKS } from "@/lib/presets/load";
import { CAMERA_GROUPS } from "@/lib/presets/schema";
import { compileImagePrompt, type CastMember, type PromptInput } from "@/lib/prompts/compile";
import { MODEL_IDS } from "@/lib/registry/models";
import { portraiusStillWorkflow } from "@/lib/workflows/comfy";

const pack = new URL("../../../custom_nodes/comfyui-portraius-characters/", import.meta.url);
const text = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;

const presets = {
  note: "Generated from the app's presets/ by npm run nodepack. Don't edit.",
  camera: Object.fromEntries(CAMERA_GROUPS.map((group) => [group, CAMERA[group].map(({ id, label, phrase, overrides }) => ({ id, label, phrase, ...(overrides ? { overrides } : {}) }))])),
  looks: LOOKS.map(({ id, label, phrase, stylised }) => ({ id, label, phrase, stylised })),
};

const lead: CastMember = { slot: "lead", name: "Marcus", kind: "person", references: ["sheet", "photo"] };
const designed: CastMember = { slot: "second", name: "Walt Harmon", kind: "person", description: "Retired harbour pilot, usually in a navy peacoat", references: ["sheet", "front"] };
const outfit: CastMember = { slot: "outfit", name: "Rust jacket", kind: "element", references: ["sheet"] };

const inputs: PromptInput[] = [
  { scene: "{lead} reading in a Tampa coffee shop, wearing the {outfit}", cast: [{ ...lead }, { ...outfit }], camera: { size: "MCU", lens: "85mm", aperture: "f2", lighting: "soft-key", look: "warm-film" }, modelId: MODEL_IDS.nanoBanana },
  { scene: "{lead} and {second} share a booth in a late-night diner. rain on the window", cast: [{ ...lead }, { ...designed }], camera: { size: "MS", angle: "low", genre: "drama", era: "1970s" }, modelId: MODEL_IDS.nanoBanana },
  { scene: "give {lead} a red scarf", cast: [{ ...lead }], camera: {}, modelId: MODEL_IDS.nanoBanana, editing: true },
  { scene: "a paper lantern sways at dusk", cast: [], camera: { lighting: "golden-hour" }, modelId: MODEL_IDS.nanoBanana },
  { scene: "{second} waves from the pier!", cast: [{ ...designed }], camera: { look: "claymation", movement: "slow-push-in" }, modelId: MODEL_IDS.nanoBanana },
  { scene: "{outfit} on a plain stand", cast: [{ ...outfit }], camera: { size: "CU", movement: "slow-push-in" }, modelId: MODEL_IDS.klingOmni },
];

const cases = {
  note: "Generated by npm run nodepack: the app's compileImagePrompt on these inputs. tests/test_compile.py checks the Python port against them.",
  cases: inputs.map((input) => ({
    input: { scene: input.scene, cast: input.cast, camera: input.camera, model_id: input.modelId, editing: Boolean(input.editing) },
    prompt: compileImagePrompt(input),
  })),
};

// The example graph: the UI format in example_workflows/ (ComfyUI's template
// browser lists every .json there), the API format beside the tests for
// npm run workflows:check.
const example = portraiusStillWorkflow();

const files: Record<string, unknown> = {
  "portraius/presets.json": presets,
  "tests/compile_cases.json": cases,
  "example_workflows/portraius-character-still.json": example.ui,
  "tests/portraius-character-still.api.json": example.api,
};

if (import.meta.env.MODE === "nodepack") {
  for (const [path, value] of Object.entries(files)) writeFileSync(new URL(path, pack), text(value));
}

describe("ComfyUI node pack", () => {
  for (const [path, value] of Object.entries(files)) {
    it(`${path} matches the app`, () => {
      expect(existsSync(new URL(path, pack)), "run npm run nodepack").toBe(true);
      expect(readFileSync(new URL(path, pack), "utf8").replace(/\r\n/g, "\n")).toBe(text(value));
    });
  }

  it("feeds the Character Prompt's prompt and references into Nano Banana 2.1, and scores its still", () => {
    const api = Object.values(example.api);
    const types = api.map((n) => n.class_type);
    expect(types).toEqual(["PortraiusLoadCharacter", "PortraiusCharacterPrompt", "GeminiNanoBanana2V2", "SaveImage", "PortraiusIdentityScore"]);
    const promptId = Object.entries(example.api).find(([, n]) => n.class_type === "PortraiusCharacterPrompt")![0];
    const still = api.find((n) => n.class_type === "GeminiNanoBanana2V2")!;
    expect(still.inputs.prompt).toEqual([promptId, 0]);
    expect(still.inputs["model.images.image_1"]).toEqual([promptId, 1]);
    const camera = api.find((n) => n.class_type === "PortraiusCharacterPrompt")!.inputs;
    for (const group of ["size", "lens", "aperture", "lighting"] as const) {
      expect(camera[group] === "none" || CAMERA[group].some((o) => o.label === camera[group]), group).toBe(true);
    }
    expect(LOOKS.some((l) => l.label === camera.look)).toBe(true);
  });

  it("covers every camera group and look", () => {
    expect(Object.keys(presets.camera)).toEqual([...CAMERA_GROUPS]);
    expect(presets.looks.length).toBe(LOOKS.length);
  });
});
